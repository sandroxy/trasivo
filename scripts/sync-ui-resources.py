#!/usr/bin/env python3
"""Keep the native localization tables identical to the reviewed public catalog."""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
catalog = json.loads((root / 'resources/strings.json').read_text())
assert set(catalog) == {'zh-Hans', 'zh-Hant', 'en', 'ja'}
keys = set(catalog['zh-Hans'])
assert all(set(values) == keys and all(isinstance(v, str) and v for v in values.values()) for values in catalog.values())
quote = lambda value: json.dumps(value, ensure_ascii=False)
java = ['// Generated by scripts/sync-ui-resources.py from resources/strings.json.',
        'package com.sandrox.trasivo.ui;', 'import java.util.HashMap;', 'import java.util.Map;',
        'final class Strings {', '  private static final Map<String, Map<String, String>> VALUES = new HashMap<>();', '  static {']
swift = ['// Generated by scripts/sync-ui-resources.py from resources/strings.json.', 'enum Strings {', '    static let values: [String: [String: String]] = [']
for language, values in catalog.items():
    java += ['    { Map<String, String> values = new HashMap<>();']
    java += [f'      values.put({quote(k)}, {quote(v)});' for k, v in values.items()]
    java += [f'      VALUES.put({quote(language)}, values); }}']
    swift += [f'        {quote(language)}: ['] + [f'            {quote(k)}: {quote(v)},' for k, v in values.items()] + ['        ],']
java += ['  }', '  static String get(String language, String key) { return VALUES.get(language).get(key); }', '}']
swift += ['    ]', '}']
outputs = {
    'native/android/trasivo-ui/src/main/java/com/sandrox/trasivo/ui/Strings.java': '\n'.join(java) + '\n',
    'native/ios/Sources/TrasivoUI/Strings.swift': '\n'.join(swift) + '\n'
}
for name, content in outputs.items():
    path = root / name
    if args.check:
        if not path.exists() or path.read_text() != content: raise SystemExit(f'Localization table is out of date: {name}')
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
print('Native localization tables verified.' if args.check else 'Native localization tables generated.')
